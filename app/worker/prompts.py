def get_dialog_analysis_prompt(transcript: str, active_blocks: list) -> str:
    """
    Генерирует системный промпт для LLM (например, OpenAI или локальной модели),
    чтобы проанализировать диалог по правилам компьютерного клуба.
    """

    # Формируем список активных блоков для текущего диалога
    blocks_text = "\n".join([f"- ID {b.id}: {b.name} (Обязательно: {b.is_required})" for b in active_blocks])

    prompt = f"""Ты — строгий аудитор контроля качества в компьютерном клубе. 
Твоя задача — проанализировать транскрипт разговора между Сотрудником и Клиентом и вернуть результат строго в формате JSON.

Транскрипт диалога:
{transcript}

Правила анализа:
1. Тип диалога: выбери один из: "новый клиент", "пополнение", "продление", "продажа", "проблема", "прочее".
2. Тональность: выбери один из: "позитив", "нейтрально", "негатив". Если "негатив", укажи причину в поле negative_reason, иначе null[cite: 1].
3. Блоки сценария: проверь, выполнил ли сотрудник следующие шаги:
{blocks_text}
Для каждого выполненного шага найди точную цитату сотрудника[cite: 1].
4. Негативные триггеры (нарушения): ищи следующие триггеры:
- "грубость и неуважение" (пренебрежительный тон, спор, отмахивание)[cite: 1]
- "оплата мимо кассы" (просьба перевести на личные реквизиты или по номеру телефона)[cite: 1]
- "хвала конкурентам" (ругает свой клуб, хвалит чужой, направляет к другим)[cite: 1]
Если найдено, обязательно приведи точную цитату[cite: 1].

Формат ответа (только валидный JSON):
{{
    "dialog_type": "...",
    "tonality": "...",
    "negative_reason": "...",
    "completed_blocks": [
        {{"block_id": 1, "quote": "точная цитата"}}
    ],
    "violations": [
        {{"trigger_type": "...", "quote": "точная цитата"}}
    ]
}}"""
    return prompt